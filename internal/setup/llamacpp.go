package setup

import (
	"fmt"
	"strings"
)

const (
	docLlamaInstall  = "https://github.com/ggml-org/llama.cpp/blob/master/docs/install.md"
	docLlamaServer   = "https://github.com/ggml-org/llama.cpp/blob/master/tools/server/README.md"
	docLlamaCLI      = "https://github.com/ggml-org/llama.cpp/blob/master/tools/cli/README.md"
	docLlamaReleases = "https://github.com/ggml-org/llama.cpp/releases"
	docLlamaBuild    = "https://github.com/ggml-org/llama.cpp/blob/master/docs/build.md"
)

const llamaReleasesAPI = "https://api.github.com/repos/ggml-org/llama.cpp/releases?per_page=5"

func (b *builder) llamacpp() error {
	pl := b.plan
	m, q := b.in.Model, b.in.Quant
	if m.HFGGUFRepo == "" {
		return fmt.Errorf("no Hugging Face GGUF repo is known for %s; download a %s GGUF yourself and run llama-server -m <file>", m.Name, q.Name)
	}
	hf := m.HFGGUFRepo + ":" + q.Name

	b.checkStep([]Command{
		b.llamaCmd(b.llamaBin("llama-server") + " --version"),
		b.any(b.curl() + " -s " + pl.Endpoint + "/health"),
	}, docLlamaInstall)

	b.add(b.llamaInstallStep())

	// download: llama-cli fetches the file into llama.cpp's cache (shared
	// with llama-server -hf) and answers one prompt, proving the build and
	// GPU backend work.
	b.add(Step{
		ID: "download-model", Kind: KindDownload,
		Title:         fmt.Sprintf("Download %s %s (%s) and test-load it", m.Name, q.Name, gbString(q.FileBytes)),
		Why:           fmt.Sprintf("`-hf %s` downloads the exact %s GGUF from Hugging Face into llama.cpp's model cache (set LLAMA_CACHE to move it; HF_TOKEN for gated repos), the same cache `llama-server -hf` uses, then loads it and answers one short prompt. A multimodal projector is downloaded too when the repo has one.", hf, q.Name),
		Commands:      []Command{b.llamaCmd(b.llamaBin("llama-cli") + " " + b.args("-hf", hf, "-c", "4096", "-n", "8", "-st", "-p", "Reply with OK"))},
		DownloadBytes: q.FileBytes,
		Confidence:    Medium,
		Docs:          []string{docLlamaCLI, docLlamaServer},
	})

	// configure: launch script with the tuned flags.
	args := b.llamaServerArgs(hf)
	var file FileEdit
	var rel string
	if b.win {
		rel = ".cyrlm/llamacpp/" + b.fileName + ".ps1"
		file = FileEdit{
			Path: "~/" + rel, Format: "text", Merge: "create",
			Content: "# Generated by cyrlm plan: " + m.Name + " " + q.Name + " on llama.cpp (" + pl.Backend + ").\n" +
				psResolveExe("llama-server") + "\n& $exe " + joinPS(args) + "\n",
			Note: "PowerShell launch script",
		}
	} else {
		rel = ".cyrlm/llamacpp/" + b.fileName + ".sh"
		file = FileEdit{
			Path: "~/" + rel, Format: "text", Merge: "create",
			Content: "#!/bin/sh\n# Generated by cyrlm plan: " + m.Name + " " + q.Name + " on llama.cpp (" + pl.Backend + ").\n" +
				`PATH="$HOME/.local/bin:$PATH"` + "\nexec llama-server " + joinSh(args) + "\n",
			Note: "POSIX shell launch script",
		}
	}
	b.add(Step{
		ID: "configure-launch-script", Kind: KindConfigure,
		Title:      "Write the llama-server launch script",
		Why:        "Keeps the tuned flags in one place so the server can be restarted the same way: " + b.llamaFlagsWhy() + " Recent builds listen on port 9931 by default, so the port is set explicitly.",
		Files:      []FileEdit{file},
		Undo:       []Command{b.os(b.rm(rel))},
		Confidence: High,
		Docs:       []string{docLlamaServer},
	})

	// start
	logRel := ".cyrlm/llamacpp/" + b.fileName + ".log"
	st := Step{
		ID: "start-server", Kind: KindStart,
		Title:      "Start llama-server on port " + fmt.Sprint(b.port),
		Confidence: Medium,
		Docs:       []string{docLlamaServer},
	}
	if b.win {
		st.Commands = []Command{
			b.os(`Start-Process powershell -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-File',` + b.home(rel) + ` -WindowStyle Minimized`),
			b.os(psWaitHealth(pl.Endpoint + "/health")),
		}
		st.Undo = []Command{b.os("Get-Process -Name llama-server -ErrorAction SilentlyContinue | Stop-Process")}
		st.Why = "Runs the launch script in a minimized PowerShell window and waits until /health reports the model is loaded. Close that window (or run the undo command) to stop the server."
	} else {
		st.Commands = []Command{
			b.os("nohup sh " + b.home(rel) + " > " + b.home(logRel) + " 2>&1 &"),
			b.os(shWaitHealth(pl.Endpoint + "/health")),
		}
		st.Undo = []Command{b.os("pkill -f " + shQuote("llama-server .*--alias "+pl.LocalModelName))}
		st.Why = "Runs the launch script in the background (log: ~/" + logRel + ") and waits until /health reports the model is loaded. Run the undo command to stop it; run the first command again after a reboot."
	}
	if b.in.Running {
		b.warn(fmt.Sprintf("A llama-server already answers on port %d; stop it before the start step, or the new server cannot bind the port.", b.port))
	}
	b.add(st)
	return nil
}

// llamaBin is how to invoke a llama.cpp binary in this plan's shell (the
// Linux release install puts symlinks in ~/.local/bin, which may not be on
// the agent's PATH yet).
func (b *builder) llamaBin(name string) string {
	switch b.in.OS {
	case "linux":
		return `PATH="$HOME/.local/bin:$PATH" ` + name
	case "windows":
		return psResolveExe(name) + "; & $exe"
	}
	return name
}

// llamaCmd labels a command that uses llamaBin: OS-specific unless the
// binary is invoked plainly (macOS).
func (b *builder) llamaCmd(run string) Command {
	if b.in.OS == "darwin" {
		return b.any(run)
	}
	return b.os(run)
}

// llamaServerArgs are the llama-server flags for the plan's settings.
func (b *builder) llamaServerArgs(hf string) []string {
	pl := b.plan
	a := []string{"-hf", hf, "-c", fmt.Sprint(pl.ContextTokens)}
	switch {
	case pl.FlashAttention:
		a = append(a, "-fa", "on")
	case b.p.Defaults.FlashAttention:
		a = append(a, "-fa", "off")
	}
	if pl.KVCacheType != "f16" {
		a = append(a, "-ctk", pl.KVCacheType, "-ctv", pl.KVCacheType)
	}
	a = append(a, "--jinja")
	if pl.Backend == "cpu" {
		a = append(a, "-ngl", "0")
	} else {
		a = append(a, "-ngl", "999")
	}
	a = append(a, "--alias", pl.LocalModelName, "--host", "127.0.0.1", "--port", fmt.Sprint(b.port))
	return a
}

func (b *builder) llamaFlagsWhy() string {
	pl := b.plan
	parts := []string{fmt.Sprintf("-c %d sets the context window (otherwise it is sized to free memory or taken from the model)", pl.ContextTokens)}
	if pl.FlashAttention {
		parts = append(parts, "-fa on forces flash attention")
	} else if b.p.Defaults.FlashAttention {
		parts = append(parts, "-fa off disables flash attention")
	}
	if pl.KVCacheType != "f16" {
		parts = append(parts, fmt.Sprintf("-ctk/-ctv %s quantize the KV cache", pl.KVCacheType))
	}
	parts = append(parts, "--jinja uses the model's chat template (needed for tool calls)")
	if pl.Backend == "cpu" {
		parts = append(parts, "-ngl 0 keeps every layer on the CPU")
	} else {
		parts = append(parts, "-ngl 999 offloads every layer to the GPU")
	}
	parts = append(parts, "--alias names the model "+pl.LocalModelName)
	return strings.Join(parts, "; ") + "."
}

func (b *builder) llamaInstallStep() Step {
	pl := b.plan
	arch := winArch(b.in.Arch)
	s := Step{ID: "install-llamacpp", Kind: KindInstall, Title: "Install llama.cpp", Docs: []string{docLlamaInstall, docLlamaReleases}}
	switch b.in.OS {
	case "darwin":
		s.Commands = []Command{b.os("brew install llama.cpp")}
		s.Undo = []Command{b.os("brew uninstall llama.cpp")}
		s.Why = "Homebrew's llama.cpp is built with Metal and updated with every release. Without Homebrew, download llama-<build>-bin-macos-" + map[string]string{"arm64": "arm64", "amd64": "x64"}[b.in.Arch] + ".tar.gz from the releases page."
		s.Confidence = High
	case "windows":
		dir := `$HOME\llama.cpp`
		switch pl.Backend {
		case "vulkan", "cpu":
			s.Commands = []Command{b.os("winget install llama.cpp")}
			s.Undo = []Command{b.os("winget uninstall llama.cpp")}
			s.Why = "The winget package (ggml.llamacpp) is the official Vulkan build, which also runs on the CPU, and is updated with every release."
			s.Confidence = High
		default:
			// main is the regex of the backend's zip; CUDA builds also need
			// the matching cudart zip.
			var main string
			switch pl.Backend {
			case "cuda":
				main = `^llama-.*-bin-win-cuda-[0-9.]+-` + arch + `\.zip$`
				s.Why = "llama.cpp publishes CUDA builds as two zips: llama-<build>-bin-win-cuda-<cuda>-" + arch + ".zip and the matching cudart-llama-bin-win-cuda-<cuda>-" + arch + ".zip (CUDA runtime DLLs); this takes the highest CUDA version and extracts both into one folder. The newest CUDA needs a recent NVIDIA driver; if llama-server reports no CUDA device, use the older CUDA zips from the releases page."
			case "rocm":
				main = `^llama-.*-bin-win-(rocm|hip)-.*` + arch + `.*\.zip$`
				s.Why = "Downloads the ROCm build (llama-<build>-bin-win-rocm-<rocm>-" + arch + ".zip); check that its GPU targets include your Radeon card."
			case "sycl":
				main = `^llama-.*-bin-win-sycl-` + arch + `\.zip$`
				s.Why = "Downloads the SYCL build for Intel GPUs (llama-<build>-bin-win-sycl-" + arch + ".zip); it needs the Intel oneAPI runtime."
			default:
				main = `^llama-.*-bin-win-cpu-` + arch + `\.zip$`
				s.Why = "Downloads the CPU build (llama-<build>-bin-win-cpu-" + arch + ".zip)."
			}
			pick := `$main = $assets | Where-Object { $_.name -match '` + main + `' } | Select-Object -First 1
$pick = @($main)`
			if pl.Backend == "cuda" {
				pick = `$main = $assets | Where-Object { $_.name -match '` + main + `' } | Sort-Object { [version][regex]::Match($_.name, '-cuda-([0-9.]+)-').Groups[1].Value } -Descending | Select-Object -First 1
$ver = [regex]::Match($main.name, '-cuda-([0-9.]+)-').Groups[1].Value
$rt = $assets | Where-Object { $_.name -eq "cudart-llama-bin-win-cuda-$ver-` + arch + `.zip" -or $_.name -match ('^cudart-.*-cuda-' + [regex]::Escape($ver) + '-` + arch + `\.zip$') } | Select-Object -First 1
$pick = @($main, $rt)`
			}
			run := `$dir = "` + dir + `"
New-Item -ItemType Directory -Force -Path $dir | Out-Null
$rel = Invoke-RestMethod '` + llamaReleasesAPI + `' | Where-Object { $_.assets.name -match '` + main + `' } | Select-Object -First 1
$assets = $rel.assets
` + pick + `
if (-not $main) { throw 'No matching release asset; pick one manually from ` + docLlamaReleases + `' }
foreach ($a in $pick) { if ($a) { $f = Join-Path $env:TEMP $a.name; Invoke-WebRequest $a.browser_download_url -OutFile $f; Expand-Archive $f -DestinationPath $dir -Force } }
$p = [Environment]::GetEnvironmentVariable('Path', 'User'); if ($p -notlike "*$dir*") { [Environment]::SetEnvironmentVariable('Path', "$p;$dir", 'User') }`
			s.Commands = []Command{b.os(run)}
			s.Undo = []Command{b.os(`Remove-Item -Recurse -Force "` + dir + `"`)}
			s.Why += " Release assets are named llama-<build>-bin-win-<backend>-<arch>.zip; this picks the newest one for your backend and adds " + dir + " to your user PATH (new terminals). Alternative for Vulkan: `winget install llama.cpp`."
			s.Confidence = Medium
		}
	default: // linux
		var asset string
		switch pl.Backend {
		case "cuda":
			asset = `/llama-[^/]*-bin-ubuntu-cuda-[0-9.]+-` + arch + `\.tar\.gz$`
		case "vulkan":
			asset = `/llama-[^/]*-bin-ubuntu-vulkan-` + arch + `\.tar\.gz$`
		case "rocm":
			asset = `/llama-[^/]*-bin-ubuntu-rocm-[0-9.]+-` + arch + `\.tar\.gz$`
		case "sycl":
			asset = `/llama-[^/]*-bin-ubuntu-sycl-fp16-` + arch + `\.tar\.gz$`
		default:
			asset = `/llama-[^/]*-bin-ubuntu-` + arch + `\.tar\.gz$`
		}
		urls := `curl -fsSL '` + llamaReleasesAPI + `' | grep -oE '"browser_download_url": *"[^"]+"' | cut -d'"' -f4`
		run := `set -e
dir="$HOME/.local/share/llama.cpp"; mkdir -p "$dir" "$HOME/.local/bin"
url=$(` + urls + ` | grep -E '` + asset + `' | sort -V | tail -n 1)
[ -n "$url" ] || { echo "no matching release asset; pick one from ` + docLlamaReleases + `" >&2; exit 1; }
curl -fL "$url" | tar -xz -C "$dir" --strip-components=1`
		if pl.Backend == "cuda" {
			run += `
ver=$(echo "$url" | sed -E 's/.*-cuda-([0-9.]+)-.*/\1/')
rt=$(` + urls + ` | grep -E "/cudart-[^/]*-cuda-$ver-` + arch + `\.tar\.gz$" | sort -V | tail -n 1)
[ -z "$rt" ] || curl -fL "$rt" | tar -xz -C "$dir" --strip-components=1`
		}
		run += `
ln -sf "$dir/llama-server" "$dir/llama-cli" "$HOME/.local/bin/"
"$dir/llama-server" --version`
		s.Commands = []Command{b.os(run)}
		s.Undo = []Command{b.os(`rm -rf "$HOME/.local/share/llama.cpp" "$HOME/.local/bin/llama-server" "$HOME/.local/bin/llama-cli"`)}
		s.Why = "Downloads the newest prebuilt release for your backend (assets are named llama-<build>-bin-ubuntu-<backend>-<arch>.tar.gz"
		if pl.Backend == "cuda" {
			s.Why += "; CUDA builds come in two CUDA versions, each with a cudart-… tarball of CUDA runtime libraries; this takes the highest version and extracts both. The newest CUDA needs a recent NVIDIA driver; if llama-server finds no CUDA device, use the older CUDA assets or build from source"
		}
		s.Why += ") into ~/.local/share/llama.cpp and links llama-server and llama-cli into ~/.local/bin. They are built on Ubuntu; on other distributions, or if a library is missing, build from source instead (cmake -B build " + cmakeFlag(pl.Backend) + " && cmake --build build --config Release) or use `brew install llama.cpp`."
		s.Confidence = Medium
		s.Docs = append(s.Docs, docLlamaBuild)
	}
	b.markInstalled(&s)
	return s
}

func cmakeFlag(backend string) string {
	switch backend {
	case "cuda":
		return "-DGGML_CUDA=ON"
	case "vulkan":
		return "-DGGML_VULKAN=ON"
	case "rocm":
		return "-DGGML_HIP=ON"
	case "sycl":
		return "-DGGML_SYCL=ON"
	}
	return ""
}

func (b *builder) rm(rel string) string {
	if b.win {
		return "Remove-Item -Force " + b.home(rel)
	}
	return "rm -f " + b.home(rel)
}

// psResolveExe sets $exe to a binary found on PATH, in winget's links
// folder or in ~\llama.cpp (PATH changes only reach new terminals).
func psResolveExe(name string) string {
	return `$exe = (Get-Command ` + name + ` -ErrorAction SilentlyContinue).Source; foreach ($c in "$env:LOCALAPPDATA\Microsoft\WinGet\Links\` + name + `.exe", "$HOME\llama.cpp\` + name + `.exe") { if (-not $exe -and (Test-Path $c)) { $exe = $c } }`
}

func shWaitHealth(url string) string {
	return "curl -fsS --retry 120 --retry-delay 5 --retry-connrefused " + url
}

func psWaitHealth(url string) string {
	return `for ($i = 0; $i -lt 120; $i++) { try { Invoke-RestMethod ` + url + ` | Out-Null; 'ready'; break } catch { Start-Sleep -Seconds 5 } }`
}

func joinSh(a []string) string {
	out := make([]string, len(a))
	for i, s := range a {
		out[i] = shQuote(s)
	}
	return strings.Join(out, " ")
}

func joinPS(a []string) string {
	out := make([]string, len(a))
	for i, s := range a {
		out[i] = psQuote(s)
	}
	return strings.Join(out, " ")
}
