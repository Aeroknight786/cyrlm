package setup

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/aeroknight786/trialm/internal/catalog"
)

const (
	docMLXServer = "https://github.com/ml-explore/mlx-lm/blob/main/mlx_lm/SERVER.md"
	docMLXReadme = "https://github.com/ml-explore/mlx-lm#installation"
)

var bitsSuffix = regexp.MustCompile(`-(\d+)bit$`)

// mlxRepo is the Hugging Face MLX repo for a quant. The catalog stores one
// repo (mlx-community/...-4bit); a different bit width swaps the suffix,
// following mlx-community's naming.
func mlxRepo(m catalog.Model, q catalog.Quant) string {
	repo := m.HFMLXRepo
	if repo == "" {
		return ""
	}
	want := regexp.MustCompile(`(\d+)bit`).FindStringSubmatch(strings.ToLower(q.Name))
	if want != nil && bitsSuffix.MatchString(repo) {
		repo = bitsSuffix.ReplaceAllString(repo, "-"+want[1]+"bit")
	}
	return repo
}

func (b *builder) mlxlm() error {
	pl := b.plan
	m, q := b.in.Model, b.in.Quant
	repo := mlxRepo(m, q)
	if repo == "" {
		return fmt.Errorf("no Hugging Face MLX repo is known for %s; mlx-lm needs one (or convert the model with mlx_lm.convert)", m.Name)
	}
	if repo != m.HFMLXRepo {
		b.warn(fmt.Sprintf("Assuming the %s MLX build is %s (the catalog lists %s); check that the repo exists.", q.Name, repo, m.HFMLXRepo))
	}
	const path = `PATH="$HOME/.local/bin:$PATH" `

	b.checkStep([]Command{
		b.os(path + "mlx_lm.server --help | head -n 1"),
		b.os("curl -s " + pl.Endpoint + "/health"),
	}, docMLXReadme)

	inst := Step{
		ID: "install-mlx-lm", Kind: KindInstall,
		Title:      "Install mlx-lm",
		Why:        "mlx-lm is a Python package for Apple Silicon. `uv tool install` puts its commands (mlx_lm.server, mlx_lm.generate) in ~/.local/bin in their own environment; without uv, use `pip install mlx-lm` (or `conda install -c conda-forge mlx-lm`).",
		Commands:   []Command{b.os("uv tool install mlx-lm")},
		Undo:       []Command{b.os("uv tool uninstall mlx-lm")},
		Confidence: High,
		Docs:       []string{docMLXReadme},
	}
	b.markInstalled(&inst)
	b.add(inst)

	b.add(Step{
		ID: "download-model", Kind: KindDownload,
		Title:         fmt.Sprintf("Download %s %s (%s) and test-load it", m.Name, q.Name, gbString(q.FileBytes)),
		Why:           fmt.Sprintf("Downloads %s into the Hugging Face cache (~/.cache/huggingface; set HF_TOKEN for gated repos) and generates a few tokens, proving the model loads. The server reuses the cached files.", repo),
		Commands:      []Command{b.os(path + "mlx_lm.generate " + b.args("--model", repo, "--prompt", "Reply with OK", "--max-tokens", "8"))},
		DownloadBytes: q.FileBytes,
		Confidence:    Medium,
		Docs:          []string{docMLXReadme},
	})

	args := []string{"--model", repo, "--host", "127.0.0.1", "--port", fmt.Sprint(b.port), "--max-tokens", fmt.Sprint(outputTokens(pl.ContextTokens))}
	why := "mlx-lm has no context-size flag: the KV cache grows with the conversation up to available memory, so the harness must keep prompts within " + fmt.Sprint(pl.ContextTokens) + " tokens. --max-tokens raises the default response limit (512 tokens) used when a client sends none."
	if pl.KVCacheType != "f16" {
		args = append(args, "--kv-bits", kvBits(pl.KVCacheType))
		why += " --kv-bits " + kvBits(pl.KVCacheType) + " quantizes the KV cache, which also turns off request batching (one request at a time)."
	}
	why += " The API model name is the repo id (" + repo + "): mlx_lm.server treats any other model name as a model to download."
	rel := ".trialm/mlx-lm/" + b.fileName + ".sh"
	b.add(Step{
		ID: "configure-launch-script", Kind: KindConfigure,
		Title: "Write the mlx_lm.server launch script",
		Why:   why,
		Files: []FileEdit{{
			Path: "~/" + rel, Format: "text", Merge: "create",
			Content: "#!/bin/sh\n# Generated by trialm plan: " + m.Name + " " + q.Name + " on mlx-lm.\n" + strings.TrimSpace(path) + "\nexec mlx_lm.server " + joinSh(args) + "\n",
			Note:    "POSIX shell launch script",
		}},
		Undo:       []Command{b.os("rm -f " + b.home(rel))},
		Confidence: High,
		Docs:       []string{docMLXServer},
	})

	logRel := ".trialm/mlx-lm/" + b.fileName + ".log"
	if b.in.Running {
		b.warn(fmt.Sprintf("A server already answers on port %d; stop it before the start step, or mlx_lm.server cannot bind the port.", b.port))
	}
	b.add(Step{
		ID: "start-server", Kind: KindStart,
		Title:      "Start mlx_lm.server on port " + fmt.Sprint(b.port),
		Why:        "Starts the launch script detached (log: ~/" + logRel + ") and returns once /health answers, so the server keeps running after this command returns. Run the undo command to stop it; run the start command again after a reboot.",
		Commands:   []Command{b.bgStart(rel, logRel, pl.Endpoint+"/health")},
		Undo:       []Command{b.os("pkill -f " + shQuote("mlx_lm.server --model "+repo))},
		Confidence: Medium,
		Docs:       []string{docMLXServer},
	})
	return nil
}
