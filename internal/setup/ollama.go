package setup

import (
	"fmt"
	"strings"

	"github.com/aeroknight786/trialm/internal/catalog"
)

const (
	docOllamaFAQEnv    = "https://docs.ollama.com/faq#how-do-i-configure-ollama-server"
	docOllamaFAQKV     = "https://docs.ollama.com/faq#how-can-i-set-the-quantization-type-for-the-k%2Fv-cache"
	docOllamaModelfile = "https://docs.ollama.com/modelfile"
	docOllamaHF        = "https://huggingface.co/docs/hub/ollama"
	docOllamaLinux     = "https://docs.ollama.com/linux"
	docOllamaReadme    = "https://github.com/ollama/ollama#download"
	docOllamaContext   = "https://docs.ollama.com/context-length"
	docOllamaOpenAICtx = "https://docs.ollama.com/api/openai-compatibility#setting-the-local-context-size"
)

// ollamaWinApp is the tray app installed by OllamaSetup.exe (per-user).
const ollamaWinApp = `$env:LOCALAPPDATA\Programs\Ollama\ollama app.exe`

type envVar struct{ name, value string }

func (b *builder) ollama() error {
	pl := b.plan
	m, q := b.in.Model, b.in.Quant
	api := pl.Endpoint + "/api/version"

	// 1. check
	b.checkStep([]Command{b.any("ollama --version"), b.any(b.curl() + " -s " + api)}, docOllamaReadme)

	// 2. install
	inst := Step{ID: "install-ollama", Kind: KindInstall, Title: "Install Ollama", Confidence: High, Docs: []string{docOllamaReadme}}
	switch b.in.OS {
	case "darwin":
		inst.Commands = []Command{
			b.os("curl -fsSL https://ollama.com/install.sh | sh"),
			b.os("open -a Ollama"),
		}
		inst.Why = "Official installer for the Ollama app (needs macOS 14+); the app runs the server on port 11434. Alternatives: download https://ollama.com/download/Ollama.dmg, or `brew install --cask ollama-app`."
		inst.Undo = []Command{b.os(`osascript -e 'quit app "Ollama"'; rm -rf /Applications/Ollama.app`)}
	case "linux":
		inst.Commands = []Command{b.os("curl -fsSL https://ollama.com/install.sh | sh")}
		inst.NeedsAdmin = true
		inst.Why = "Official install script: installs /usr/local/bin/ollama (with CUDA/ROCm libraries when it finds a GPU) and an `ollama` systemd service that starts the server on port 11434. It uses sudo."
		inst.Docs = append(inst.Docs, docOllamaLinux)
	case "windows":
		inst.Commands = []Command{b.os("irm https://ollama.com/install.ps1 | iex")}
		inst.Why = "Official installer; installs per user (no administrator rights) and starts Ollama in the system tray. Alternatives: `winget install --id Ollama.Ollama -e`, or download https://ollama.com/download/OllamaSetup.exe."
		inst.Undo = []Command{b.os("winget uninstall --id Ollama.Ollama -e")}
	}
	b.markInstalled(&inst)
	b.add(inst)

	// 3. download
	src, fromHF := ollamaSource(m.HFGGUFRepo, m.OllamaTag, q.HFTag(), m.Quants)
	if src == "" {
		return fmt.Errorf("%s has neither a Hugging Face GGUF repo nor an Ollama tag", m.Name)
	}
	dl := Step{
		ID: "download-model", Kind: KindDownload,
		Title:         fmt.Sprintf("Download %s %s (%s)", m.Name, q.Name, gbString(q.FileBytes)),
		DownloadBytes: q.FileBytes,
		Undo:          []Command{b.any("ollama rm " + b.q(src))},
		Confidence:    High,
		Docs:          []string{docOllamaHF},
	}
	if fromHF {
		dl.Why = fmt.Sprintf("Pulls the exact %s GGUF from Hugging Face (%s) — the file triaLM's prediction is based on. If Ollama reports an unsupported architecture for this file, use the library build instead: `ollama pull %s`.", q.Name, m.HFGGUFRepo, m.OllamaTag)
		if !strings.Contains(m.OllamaTag, ":") { // no Ollama library build to fall back to
			dl.Why = fmt.Sprintf("Pulls the exact %s GGUF from Hugging Face (%s) — the file triaLM's prediction is based on.", q.Name, m.HFGGUFRepo)
		}
	} else {
		dl.Why = fmt.Sprintf("No Hugging Face GGUF repo is known for %s, so this pulls Ollama's library build %s; its file may differ slightly from the predicted %s.", m.Name, src, q.Name)
		dl.Confidence = Medium
		dl.Docs = []string{"https://ollama.com/library"}
	}
	if b.in.Installed && !b.in.Running {
		// The server must be up to pull.
		dl.Commands = append(dl.Commands, b.ollamaEnsureRunning())
		if b.in.OS == "linux" {
			dl.NeedsAdmin = true
		}
	}
	dl.Commands = append(dl.Commands, b.any("ollama pull "+b.q(src)))
	b.add(dl)

	// 4. configure: Modelfile with the context window.
	mfRel := ".trialm/ollama/" + b.fileName + ".Modelfile"
	modelfile := fmt.Sprintf("# Generated by trialm plan: %s %s on Ollama.\nFROM %s\nPARAMETER num_ctx %d\n", m.Name, q.Name, src, pl.ContextTokens)
	b.add(Step{
		ID: "configure-modelfile", Kind: KindConfigure,
		Title: fmt.Sprintf("Create %s with a %d-token context", pl.LocalModelName, pl.ContextTokens),
		Why: fmt.Sprintf("Ollama's default context depends on GPU memory (often 4096 tokens) and the OpenAI/Anthropic-compatible APIs cannot change it per request; a Modelfile with num_ctx fixes it for this model only. The new model shares the downloaded weights (no extra disk). Use %s as the model name in your harness.",
			pl.LocalModelName),
		Files: []FileEdit{{
			Path: "~/" + mfRel, Format: "modelfile", Content: modelfile, Merge: "create",
		}},
		Commands:   []Command{b.any("ollama create " + b.q(pl.LocalModelName) + " -f " + b.home(mfRel))},
		Undo:       []Command{b.any("ollama rm " + b.q(pl.LocalModelName))},
		Confidence: High,
		Docs:       []string{docOllamaModelfile, docOllamaOpenAICtx, docOllamaContext},
	})

	// 5. service: server-wide environment variables that differ from defaults.
	if env := b.ollamaEnv(); len(env) > 0 {
		b.ollamaServiceSteps(env)
	}

	// 6. start: load the model now and show what Ollama allocated.
	st := Step{
		ID: "start-model", Kind: KindStart,
		Title:      "Load " + pl.LocalModelName + " and check GPU placement",
		Confidence: High,
		Docs:       []string{docOllamaContext},
		Undo:       []Command{b.any("ollama stop " + b.q(pl.LocalModelName))},
	}
	st.Why = fmt.Sprintf("Preloads the model so the first harness request does not pay the load time. In `ollama ps`, CONTEXT should read %d and PROCESSOR should read 100%% GPU (anything else means part of the model runs on the CPU and will be much slower than predicted).", pl.ContextTokens)
	if b.win {
		st.Commands = []Command{
			b.os(fmt.Sprintf(`Invoke-RestMethod -Method Post -Uri %s/api/generate -Body '{"model": "%s"}' | Out-Null`, pl.Endpoint, pl.LocalModelName)),
			b.any("ollama ps"),
		}
	} else {
		st.Commands = []Command{
			b.os(fmt.Sprintf(`curl -s %s/api/generate -d '{"model": "%s"}' >/dev/null`, pl.Endpoint, pl.LocalModelName)),
			b.any("ollama ps"),
		}
	}
	b.add(st)
	return nil
}

// ollamaSource is what to pull: hf.co/<repo>:<quant> when the GGUF repo is
// known, else the library tag (with a quant suffix for non-default quants).
func ollamaSource(hfRepo, tag, quant string, quants []catalog.Quant) (string, bool) {
	if hfRepo != "" {
		return "hf.co/" + hfRepo + ":" + quant, true
	}
	if tag == "" {
		return "", false
	}
	if len(quants) > 0 && !strings.EqualFold(quants[0].Name, quant) {
		return tag + "-" + strings.ToLower(quant), false
	}
	return tag, false
}

// ollamaEnv lists the server environment variables whose values differ
// from Ollama's defaults for the chosen settings.
func (b *builder) ollamaEnv() []envVar {
	d := b.p.Defaults
	pl := b.plan
	var env []envVar
	if pl.FlashAttention != d.FlashAttention {
		v := "0"
		if pl.FlashAttention {
			v = "1"
		}
		env = append(env, envVar{"OLLAMA_FLASH_ATTENTION", v})
	}
	defKV := strings.ToLower(d.KVCacheType)
	if defKV == "" {
		defKV = "f16"
	}
	if pl.KVCacheType != defKV {
		env = append(env, envVar{"OLLAMA_KV_CACHE_TYPE", pl.KVCacheType})
	}
	if pl.KeepAliveS != d.KeepAliveS {
		env = append(env, envVar{"OLLAMA_KEEP_ALIVE", fmt.Sprint(pl.KeepAliveS)})
	}
	return env
}

func envSummary(env []envVar) string {
	parts := make([]string, len(env))
	for i, e := range env {
		parts[i] = e.name + "=" + e.value
	}
	return strings.Join(parts, ", ")
}

func (b *builder) ollamaEnvWhy(env []envVar) string {
	var why []string
	for _, e := range env {
		switch e.name {
		case "OLLAMA_FLASH_ATTENTION":
			why = append(why, "flash attention "+map[string]string{"1": "on", "0": "off"}[e.value])
		case "OLLAMA_KV_CACHE_TYPE":
			why = append(why, e.value+" KV cache (about half the memory of f16; applies to every model this server runs and needs flash attention)")
		case "OLLAMA_KEEP_ALIVE":
			if e.value == "-1" {
				why = append(why, "never unload the model when idle (default: 5 minutes, after which the next request reloads it and re-processes the whole prompt)")
			} else {
				why = append(why, "unload after "+e.value+" idle seconds")
			}
		}
	}
	return "Server-wide settings for " + strings.Join(why, "; ") + ". Ollama reads them only from the server's environment at start-up, so they are set persistently and the server is restarted. Running models are unloaded by the restart."
}

func (b *builder) ollamaServiceSteps(env []envVar) {
	st := Step{
		ID: "service-ollama-env", Kind: KindService,
		Title:      "Set Ollama server settings: " + envSummary(env),
		Why:        b.ollamaEnvWhy(env),
		Restart:    "Ollama server (this step restarts it)",
		Confidence: High,
		Docs:       []string{docOllamaFAQEnv, docOllamaFAQKV},
	}
	switch b.in.OS {
	case "darwin":
		for _, e := range env {
			st.Commands = append(st.Commands, b.os("launchctl setenv "+e.name+" "+shQuote(e.value)))
			st.Undo = append(st.Undo, b.os("launchctl unsetenv "+e.name))
		}
		st.Commands = append(st.Commands, b.os(`osascript -e 'quit app "Ollama"'; sleep 3; open -a Ollama`))
		st.Undo = append(st.Undo, b.os(`osascript -e 'quit app "Ollama"'; sleep 3; open -a Ollama`))
		st.Why += " launchctl settings last until logout/reboot; the next (optional) step makes them permanent. If you run `ollama serve` yourself or via `brew services`, set the variables in that environment instead."
	case "linux":
		lines := []string{"'[Service]'"}
		for _, e := range env {
			lines = append(lines, shQuote(`Environment="`+e.name+"="+e.value+`"`))
		}
		dropin := "/etc/systemd/system/ollama.service.d/trialm.conf"
		st.Commands = []Command{
			b.os("sudo mkdir -p /etc/systemd/system/ollama.service.d"),
			b.os("printf '%s\\n' " + strings.Join(lines, " ") + " | sudo tee " + dropin + " >/dev/null"),
			b.os("sudo systemctl daemon-reload"),
			b.os("sudo systemctl restart ollama"),
		}
		st.Undo = []Command{
			b.os("sudo rm -f " + dropin),
			b.os("sudo systemctl daemon-reload"),
			b.os("sudo systemctl restart ollama"),
		}
		st.NeedsAdmin = true
		st.Why += " This writes a systemd drop-in (same effect as `sudo systemctl edit ollama`) for the service the install script created. If you run `ollama serve` yourself, export the variables in that shell instead."
		b.warn("Restarting the Ollama service unloads any running models.")
	case "windows":
		var set, unset []string
		for _, e := range env {
			set = append(set, fmt.Sprintf("[Environment]::SetEnvironmentVariable('%s', '%s', 'User'); Set-Item -Path env:%s -Value '%s'", e.name, e.value, e.name, e.value))
			unset = append(unset, fmt.Sprintf("[Environment]::SetEnvironmentVariable('%s', $null, 'User')", e.name))
		}
		restart := "Get-Process -Name 'ollama app','ollama' -ErrorAction SilentlyContinue | Stop-Process -Force\nStart-Sleep -Seconds 3\nStart-Process \"" + ollamaWinApp + "\""
		st.Commands = []Command{b.os(strings.Join(set, "\n") + "\n" + restart)}
		st.Undo = []Command{b.os(strings.Join(unset, "\n") + "\n" + restart)}
		st.Confidence = Medium
		st.Why += " The variables are saved for your user account, and Ollama is quit and restarted from the same PowerShell session so it sees them (Ollama only reads them at start-up). If the tray app is not at the usual per-user location, quit Ollama from the system tray and start it from the Start menu instead."
		b.warn("On Windows, Ollama picks up the new server settings only after it is quit from the system tray and started again (the settings step does this).")
	}
	b.add(st)

	if b.in.OS == "darwin" {
		label := "com.trialm.ollama-env"
		rel := "Library/LaunchAgents/" + label + ".plist"
		var sets []string
		for _, e := range env {
			sets = append(sets, "launchctl setenv "+e.name+" "+shQuote(e.value))
		}
		plist := `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>` + label + `</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>-c</string>
    <string>` + xmlEscape(strings.Join(sets, "; ")) + `</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
</dict>
</plist>
`
		b.add(Step{
			ID: "service-ollama-env-persist", Kind: KindService,
			Title:    "Keep the Ollama settings after a reboot (macOS)",
			Why:      "launchctl setenv does not survive a logout. This LaunchAgent sets the same variables at every login. If Ollama starts before it at login, quit and reopen Ollama once.",
			Optional: true,
			Files:    []FileEdit{{Path: "~/" + rel, Format: "text", Content: plist, Merge: "create", Note: "launchd property list"}},
			Commands: []Command{b.os(`launchctl bootstrap gui/$(id -u) "$HOME/` + rel + `"`)},
			Undo: []Command{
				b.os("launchctl bootout gui/$(id -u)/" + label),
				b.os(`rm -f "$HOME/` + rel + `"`),
			},
			Confidence: Low,
			Docs:       []string{docOllamaFAQEnv},
		})
	}
}

// ollamaEnsureRunning starts the Ollama server if it is not running.
func (b *builder) ollamaEnsureRunning() Command {
	switch b.in.OS {
	case "darwin":
		return b.os("open -a Ollama")
	case "windows":
		return b.os(`if (-not (Get-Process -Name 'ollama' -ErrorAction SilentlyContinue)) { Start-Process "` + ollamaWinApp + `"; Start-Sleep -Seconds 5 }`)
	}
	return b.os("systemctl is-active --quiet ollama || sudo systemctl start ollama")
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;").Replace(s)
}
