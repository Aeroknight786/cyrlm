// Package paths owns triaLM's home directory (~/.trialm), its environment
// variables, and the one-time migration from the old cyrlm name.
//
// Until v0.3 every TRIALM_* variable falls back to its CYRLM_* twin, and a
// ~/.cyrlm directory (plus the old per-OS config directory) is moved into
// ~/.trialm on first run, with a symlink left at ~/.cyrlm so setups and
// scripts written by cyrlm keep working.
package paths

import (
	"bytes"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// DirName is the home directory's name under the user's home.
const DirName = ".trialm"

// Getenv returns TRIALM_<name>, else the old CYRLM_<name> (kept for one
// release), else "".
func Getenv(name string) string {
	if v := os.Getenv("TRIALM_" + name); v != "" {
		return v
	}
	return os.Getenv("CYRLM_" + name)
}

// LookupEnv is os.Getenv for a variable named by the user (for example
// through --key-env), with the same CYRLM_ fallback for TRIALM_ names.
func LookupEnv(name string) string {
	if v := os.Getenv(name); v != "" {
		return v
	}
	if rest, ok := strings.CutPrefix(name, "TRIALM_"); ok {
		return os.Getenv("CYRLM_" + rest)
	}
	return ""
}

// Home returns triaLM's home directory: $TRIALM_HOME (or $CYRLM_HOME), else
// ~/.trialm. It does not create it.
func Home() (string, error) {
	if d := Getenv("HOME"); d != "" {
		return d, nil
	}
	h, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(h, DirName), nil
}

// Migration reports what Migrate did.
type Migration struct {
	MovedFrom      string   // the old ~/.cyrlm, now a symlink to Home
	ConfigCopied   []string // files copied from the old config directory
	ScriptsUpdated []string // owned files whose cyrlm paths were rewritten
}

// Did reports whether anything changed.
func (m Migration) Did() bool {
	return m.MovedFrom != "" || len(m.ConfigCopied) > 0 || len(m.ScriptsUpdated) > 0
}

// Migrate moves a cyrlm installation into ~/.trialm. It is a no-op when
// TRIALM_HOME/CYRLM_HOME is set, when ~/.trialm already exists, or when
// there is nothing to migrate. userHome is the user's home directory and
// oldConfigDir the old per-OS config directory (os.UserConfigDir()/cyrlm);
// both are parameters so tests can use fixtures.
func Migrate(userHome, oldConfigDir string) (Migration, error) {
	var m Migration
	if Getenv("HOME") != "" || userHome == "" {
		return m, nil
	}
	home := filepath.Join(userHome, DirName)
	if _, err := os.Lstat(home); err == nil {
		return m, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return m, err
	}
	old := filepath.Join(userHome, ".cyrlm")
	if fi, err := os.Lstat(old); err == nil && fi.IsDir() {
		// Same filesystem, so this is one atomic rename.
		if err := os.Rename(old, home); err != nil {
			return m, err
		}
		m.MovedFrom = old
		// The symlink keeps paths baked into existing setups working; a
		// failure (e.g. Windows without symlink rights) is not fatal
		// because the owned files are rewritten below.
		_ = os.Symlink(home, old)
	}
	if oldConfigDir != "" {
		copied, err := copyMissing(oldConfigDir, home)
		if err != nil {
			return m, err
		}
		m.ConfigCopied = copied
	}
	if m.MovedFrom != "" {
		updated, err := rewriteOwned(home)
		if err != nil {
			return m, err
		}
		m.ScriptsUpdated = updated
	}
	return m, nil
}

// copyMissing copies the regular files under src (config.json, results/…)
// into dst unless dst already has them, with owner-only permissions. src is
// left alone, so an older cyrlm binary still finds its config.
func copyMissing(src, dst string) ([]string, error) {
	var copied []string
	err := filepath.WalkDir(src, func(p string, e fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		if !e.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		to := filepath.Join(dst, rel)
		if _, err := os.Lstat(to); err == nil {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(to), 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(to, b, 0o600); err != nil {
			return err
		}
		copied = append(copied, to)
		return nil
	})
	return copied, err
}

// ownedDirs hold the scripts, Modelfiles and harness files that cyrlm's
// setup plans wrote; they may embed ~/.cyrlm paths and `cyrlm` commands.
var ownedDirs = []string{"llamacpp", "mlx-lm", "ollama", "harness"}

var rewrites = []struct{ old, new string }{
	{"/.cyrlm/", "/" + DirName + "/"},
	{`\.cyrlm\`, `\` + DirName + `\`},
	{"cyrlm bg ", "trialm bg "},
	{"cyrlm bridge ", "trialm bridge "},
	{"Generated by cyrlm plan", "Generated by trialm plan"},
}

func rewriteOwned(home string) ([]string, error) {
	var updated []string
	for _, d := range ownedDirs {
		err := filepath.WalkDir(filepath.Join(home, d), func(p string, e fs.DirEntry, err error) error {
			if err != nil {
				if errors.Is(err, fs.ErrNotExist) {
					return nil
				}
				return err
			}
			if !e.Type().IsRegular() || strings.HasSuffix(p, ".log") {
				return nil
			}
			b, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			nb := b
			for _, r := range rewrites {
				nb = bytes.ReplaceAll(nb, []byte(r.old), []byte(r.new))
			}
			if bytes.Equal(nb, b) {
				return nil
			}
			info, err := e.Info()
			if err != nil {
				return err
			}
			// Write next to the file and rename, so a crash never leaves
			// a half-written script.
			tmp := p + ".tmp-migrate"
			if err := os.WriteFile(tmp, nb, info.Mode().Perm()); err != nil {
				return err
			}
			if err := os.Rename(tmp, p); err != nil {
				return err
			}
			updated = append(updated, p)
			return nil
		})
		if err != nil {
			return updated, err
		}
	}
	return updated, nil
}
