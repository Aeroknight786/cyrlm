package paths

import (
	"os"
	"path/filepath"
	goruntime "runtime"
	"strings"
	"testing"
)

func write(t *testing.T, p, content string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), mode); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func clearEnv(t *testing.T) {
	for _, k := range []string{"TRIALM_HOME", "CYRLM_HOME"} {
		t.Setenv(k, "")
	}
}

// An upgrade from cyrlm keeps the key, the results and the setups, and the
// old ~/.cyrlm paths keep working.
func TestMigrateFromCyrlm(t *testing.T) {
	clearEnv(t)
	userHome := t.TempDir()
	oldConfig := filepath.Join(t.TempDir(), "cyrlm")
	write(t, filepath.Join(oldConfig, "config.json"), `{"openrouter_key":"sk-or-test"}`, 0o600)
	write(t, filepath.Join(oldConfig, "results", "r1.json"), `{}`, 0o600)
	script := filepath.Join(userHome, ".cyrlm", "llamacpp", "qwen-cyrlm.sh")
	write(t, script, "#!/bin/sh\n# Generated by cyrlm plan: Qwen\nexec llama-server --alias qwen-cyrlm\n", 0o755)
	settings := filepath.Join(userHome, ".cyrlm", "harness", "claude-code-llamacpp.json")
	write(t, settings, `{"apiKeyHelper":"cat $HOME/.cyrlm/key"}`, 0o600)
	write(t, filepath.Join(userHome, ".cyrlm", "logs", "try.log"), "cyrlm bg log line /.cyrlm/", 0o644)

	m, err := Migrate(userHome, oldConfig)
	if err != nil {
		t.Fatal(err)
	}
	if !m.Did() || m.MovedFrom == "" {
		t.Fatalf("expected a migration, got %+v", m)
	}
	home := filepath.Join(userHome, ".trialm")
	if got := read(t, filepath.Join(home, "config.json")); !strings.Contains(got, "sk-or-test") {
		t.Errorf("key not migrated: %s", got)
	}
	if _, err := os.Stat(filepath.Join(home, "results", "r1.json")); err != nil {
		t.Errorf("results not migrated: %v", err)
	}
	newScript := filepath.Join(home, "llamacpp", "qwen-cyrlm.sh")
	got := read(t, newScript)
	if !strings.Contains(got, "Generated by trialm plan") || !strings.Contains(got, "--alias qwen-cyrlm") {
		t.Errorf("script not rewritten correctly (the model alias must stay): %s", got)
	}
	if fi, err := os.Stat(newScript); err != nil || fi.Mode().Perm() != 0o755 {
		t.Errorf("script mode not kept: %v %v", fi, err)
	}
	if got := read(t, filepath.Join(home, "harness", "claude-code-llamacpp.json")); !strings.Contains(got, "$HOME/.trialm/key") {
		t.Errorf("harness file not rewritten: %s", got)
	}
	if got := read(t, filepath.Join(home, "logs", "try.log")); !strings.Contains(got, "/.cyrlm/") {
		t.Errorf("logs must not be rewritten: %s", got)
	}
	if goruntime.GOOS != "windows" {
		// The old path still resolves, through the symlink.
		if got := read(t, filepath.Join(userHome, ".cyrlm", "llamacpp", "qwen-cyrlm.sh")); !strings.Contains(got, "trialm") {
			t.Errorf("~/.cyrlm does not point at ~/.trialm: %s", got)
		}
	}
	// The old config directory is left for older binaries.
	if _, err := os.Stat(filepath.Join(oldConfig, "config.json")); err != nil {
		t.Errorf("old config removed: %v", err)
	}

	// A second run does nothing.
	m2, err := Migrate(userHome, oldConfig)
	if err != nil || m2.Did() {
		t.Fatalf("second migration should be a no-op: %+v %v", m2, err)
	}
}

// A user who only ever logged in (no ~/.cyrlm) still keeps the key.
func TestMigrateConfigOnly(t *testing.T) {
	clearEnv(t)
	userHome := t.TempDir()
	oldConfig := filepath.Join(t.TempDir(), "cyrlm")
	write(t, filepath.Join(oldConfig, "config.json"), `{"openrouter_key":"k"}`, 0o600)
	m, err := Migrate(userHome, oldConfig)
	if err != nil {
		t.Fatal(err)
	}
	if m.MovedFrom != "" || len(m.ConfigCopied) != 1 {
		t.Fatalf("got %+v", m)
	}
	if _, err := os.Lstat(filepath.Join(userHome, ".cyrlm")); err == nil {
		t.Error("no ~/.cyrlm symlink should be created when there was none")
	}
	fi, err := os.Stat(filepath.Join(userHome, ".trialm", "config.json"))
	if err != nil {
		t.Fatal(err)
	}
	if goruntime.GOOS != "windows" && fi.Mode().Perm() != 0o600 {
		t.Errorf("config mode %v, want 0600", fi.Mode().Perm())
	}
}

func TestMigrateSkips(t *testing.T) {
	clearEnv(t)
	userHome := t.TempDir()
	write(t, filepath.Join(userHome, ".cyrlm", "x"), "x", 0o600)
	write(t, filepath.Join(userHome, ".trialm", "y"), "y", 0o600)
	if m, err := Migrate(userHome, ""); err != nil || m.Did() {
		t.Fatalf("existing ~/.trialm must win: %+v %v", m, err)
	}
	if _, err := os.Stat(filepath.Join(userHome, ".cyrlm", "x")); err != nil {
		t.Error("~/.cyrlm must be left alone")
	}

	t.Setenv("TRIALM_HOME", t.TempDir())
	other := t.TempDir()
	write(t, filepath.Join(other, ".cyrlm", "x"), "x", 0o600)
	if m, err := Migrate(other, ""); err != nil || m.Did() {
		t.Fatalf("TRIALM_HOME set: no migration expected: %+v %v", m, err)
	}
}

func TestEnvFallback(t *testing.T) {
	t.Setenv("TRIALM_KEY", "")
	t.Setenv("CYRLM_KEY", "old")
	if got := Getenv("KEY"); got != "old" {
		t.Errorf("fallback: got %q", got)
	}
	t.Setenv("TRIALM_KEY", "new")
	if got := Getenv("KEY"); got != "new" {
		t.Errorf("TRIALM_ wins: got %q", got)
	}
	t.Setenv("TRIALM_UPSTREAM_API_KEY", "")
	t.Setenv("CYRLM_UPSTREAM_API_KEY", "u")
	if got := LookupEnv("TRIALM_UPSTREAM_API_KEY"); got != "u" {
		t.Errorf("LookupEnv fallback: got %q", got)
	}
	if got := LookupEnv("OPENROUTER_API_KEY_UNSET_X"); got != "" {
		t.Errorf("non-trialm names have no fallback: %q", got)
	}

	t.Setenv("TRIALM_HOME", "")
	t.Setenv("CYRLM_HOME", "/tmp/oldhome")
	if h, _ := Home(); h != "/tmp/oldhome" {
		t.Errorf("Home fallback: %q", h)
	}
}
